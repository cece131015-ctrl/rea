const LIMITATIONS = [
  "Only response bytes retained in the capture are mirrored; nothing is refetched. Resources the page did not load during the capture, such as unvisited links, unused srcset candidates or lazy content, are absent.",
  "files/ holds the exact retained bytes, verified against the capture digests. view/ holds derived copies of UTF-8 HTML and CSS whose captured references point to local relative paths; uncaptured relative references were made absolute and need network access when opened.",
  "JavaScript is never rewritten: root-relative or computed fetch, import and asset URLs inside scripts stay unresolved, Chromium does not run module scripts from file:// URLs, and opening the view runs the captured JavaScript in your browser.",
  "integrity and crossorigin attributes were removed only from elements whose references were rewritten to local copies.",
  "index.html at the output root is a page generated by REA that opens the entry document; it is not captured content.",
];
const NO_VIEW_LIMITATION =
  "Some HTML or CSS bytes were not valid UTF-8, or used non-ASCII bytes under another declared charset; their references were not rewritten and only the exact files are available.";
const NO_URL_VIEW_LIMITATION =
  "Some HTML or CSS responses have no absolute URL to resolve their references against; only their exact files are available.";
const MAX_REDIRECT_HOPS = 20;
// Absolute file:// links do not survive a moved directory, so the generated
// page uses a relative link; HTML-escaping keeps it inert.
const indexPage = (target: string): Buffer => {
  const href = target
    .split("/")
    .map(encodeURIComponent)
    .join("/")
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;");
  return Buffer.from(
    `<!doctype html>\n<meta charset="utf-8">\n<title>REA website mirror</title>\n<meta http-equiv="refresh" content="0; url=${href}">\n<p>Generated by REA. <a href="${href}">Open the mirrored page</a>.</p>\n`,
  );
};

/** The capture file the mirror records and, for live clones, persists. */
export interface MirrorCaptureFile {
  readonly path: string;
  readonly sha256: string;
  /** Exact capture JSON to write as capture.json, produced in bounded parts. */
  readonly persist?: {
    readonly bytes: number;
    readonly parts: () => Iterable<string>;
  };
}

export interface PublishWebMirrorOptions {
  readonly operation: Extract<
    WebCaptureExportOperation,
    "export_web_mirror" | "clone_website"
  >;
  readonly resources: ArtifactResourceScope;
  readonly signal?: AbortSignal;
  readonly error: WebCaptureExportErrorFactory;
}

type ViewKind = "html" | "css";

const viewKind = (file: PlannedMirrorFile): ViewKind | undefined =>
  file.essence === "text/html"
    ? "html"
    : file.essence === "text/css"
      ? "css"
      : undefined;

const UTF8 = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true });

// Single-byte charsets that encode ASCII identically.
const ASCII_COMPATIBLE_CHARSET =
  /^(?:iso-8859-\d{1,2}|latin1|windows-125\d|cp125\d|ascii)$/u;

/**
 * Decode bytes eligible for a rewritten view, or undefined when unsafe.
 * Splicing preserves every untouched byte, so UTF-8 text is safe, and pure
 * ASCII is safe under any ASCII-compatible declared charset.
 */
const viewText = (
  file: PlannedMirrorFile,
  bytes: Buffer,
): string | undefined => {
  const charset = (
    file.body.media_type === null
      ? undefined
      : mediaTypeParameter(file.body.media_type, "charset")
  )?.toLowerCase();
  const utf8 =
    charset === undefined ||
    charset === "utf-8" ||
    charset === "utf8" ||
    charset === "us-ascii";
  if (
    !utf8 &&
    !(
      ASCII_COMPATIBLE_CHARSET.test(charset) &&
      bytes.every((byte) => byte < 0x80)
    )
  )
    return undefined;
  try {
    return UTF8.decode(bytes);
  } catch {
    return undefined;
  }
};

type ExportedLayout = Pick<
  Extract<WebMirrorResource["content"], { state: "exported" }>,
  "layout" | "layout_reason"
>;
type ViewRecord = NonNullable<WebMirrorResource["view"]>;
type MirrorPlan = ReturnType<typeof planWebMirror>;

/** Final exact-file placement, after any destination case-collision fallback. */
interface WrittenFiles {
  readonly paths: readonly string[];
  readonly layouts: readonly ExportedLayout[];
  /** Decoded text of files eligible for a rewritten view, by file index. */
  readonly texts: ReadonlyMap<number, string>;
}

/**
 * Publish exact retained bytes, rewritten HTML/CSS views, a generated entry
 * page and a manifest into one exclusively created absent directory.
 */
export const publishWebMirror = async (
  outputDirectory: string,
  capture: SelectedMirrorCapture,
  captureFile: MirrorCaptureFile,
  options: PublishWebMirrorOptions,
): Promise<WebMirrorExportResult> => {
  const plan = planWebMirror(capture.resources);
  const { signal } = options;
  return publishOutputTree<WebMirrorExportResult>(
    {
      operation: options.operation,
      outputDirectory,
      resources: options.resources,
      ...(signal === undefined ? {} : { signal }),
      error: options.error,
      partialObservation: (result) => ({ kind: "web-mirror-export", result }),
    },
    async ({ tree, assertActive }) => {
      const { persist } = captureFile;
      if (persist !== undefined)
        await tree.write(
          "capture.json",
          Readable.from(utf8Chunks(persist.parts())),
          { sha256: captureFile.sha256, bytes: persist.bytes },
          signal,
        );
      // Exact files first: case-collision fallbacks fix final paths before
      // any view links to them.
      const written = await writeExactFiles(tree, plan, assertActive, signal);
      const views = await writeViews(
        tree,
        capture,
        plan,
        written,
        assertActive,
        signal,
      );
      const records = resourceRecords(capture, plan, written, views);
      const { entry, limitation: entryLimitation } = entryRecord(
        capture,
        records,
      );
      if (entry !== null)
        await writeIndexPage(tree, entry.view_path ?? entry.file_path, signal);
      const manifest = webMirrorManifestSchema.parse({
        capture: {
          path:
            captureFile.persist === undefined
              ? captureFile.path
              : join(tree.outputRoot, "capture.json"),
          sha256: captureFile.sha256,
          kind: "browser-scenario",
          source_evidence_id: capture.sourceEvidenceId,
          completeness: capture.completeness,
        },
        output_directory: tree.outputRoot,
        entry,
        resources: records,
        coverage: coverage(plan, records, views),
        limitations: [
          ...mirrorLimitations(capture, plan, written.texts),
          ...(entryLimitation === undefined ? [] : [entryLimitation]),
        ],
      });
      const persisted = manifestBytes(manifest);
      return {
        manifest: persisted,
        result: inlineResult(manifest, {
          path: join(tree.outputRoot, "manifest.json"),
          sha256: persisted.sha256,
          bytes: persisted.bytes.length,
        }),
      };
    },
  );
};

function* utf8Chunks(parts: Iterable<string>): Generator<Buffer> {
  for (const part of parts) yield Buffer.from(part, "utf8");
}

const writeExactFiles = async (
  tree: SafeOutputTree,
  plan: MirrorPlan,
  assertActive: () => void,
  signal: AbortSignal | undefined,
): Promise<WrittenFiles> => {
  const paths: string[] = [];
  const layouts: ExportedLayout[] = [];
  const texts = new Map<number, string>();
  for (const [index, file] of plan.files.entries()) {
    assertActive();
    const bytes = responseBodyBytes(file.body);
    const written = await writeExactFile(tree, file, bytes, signal);
    paths.push(written.path);
    layouts.push(written.layout);
    if (viewKind(file) !== undefined && URL.canParse(file.url)) {
      const text = viewText(file, bytes);
      if (text !== undefined) texts.set(index, text);
    }
  }
  return { paths, layouts, texts };
};

const writeViews = async (
  tree: SafeOutputTree,
  capture: SelectedMirrorCapture,
  plan: MirrorPlan,
  written: WrittenFiles,
  assertActive: () => void,
  signal: AbortSignal | undefined,
): Promise<Map<number, ViewRecord>> => {
  // Files of identical directories under files/ and view/ share one name
  // policy, so a view path is free whenever its exact path was.
  const viewPaths = new Map<number, string>();
  for (const index of written.texts.keys())
    viewPaths.set(
      index,
      `view/${(written.paths[index] ?? "").slice("files/".length)}`,
    );
  const byUrl = urlTargets(capture, plan);
  const lookup = (url: string): string | undefined => {
    const file = byUrl.get(url);
    return file === undefined
      ? undefined
      : (viewPaths.get(file) ?? written.paths[file]);
  };
  const views = new Map<number, ViewRecord>();
  for (const [index, path] of viewPaths) {
    assertActive();
    const file = plan.files[index];
    const text = written.texts.get(index);
    if (file === undefined || text === undefined) continue;
    const rewritten = rewriteView(file, text, path, lookup);
    const bytes = Buffer.from(rewritten.text);
    const sha256 = createHash("sha256").update(bytes).digest("hex");
    await writeTreeFile(tree, path, bytes, sha256, signal);
    views.set(index, {
      relative_path: path,
      sha256,
      bytes: bytes.length,
      rewritten_references: rewritten.rewritten,
      unresolved_references: rewritten.unresolved,
      removed_attributes: rewritten.removedAttributes,
    });
  }
  return views;
};

const resourceRecords = (
  capture: SelectedMirrorCapture,
  plan: MirrorPlan,
  written: WrittenFiles,
  views: ReadonlyMap<number, ViewRecord>,
): WebMirrorResource[] =>
  capture.resources.map((resource, index): WebMirrorResource => {
    const outcome = plan.resources[index];
    const base = {
      source: resource.source,
      method: resource.method,
      url: resource.url,
      resource_type: resource.resource_type,
      media_type:
        resource.content.state === "captured"
          ? resource.content.media_type
          : null,
    };
    const file =
      outcome?.kind === "file" ? plan.files[outcome.file] : undefined;
    if (outcome?.kind === "file" && file !== undefined)
      return {
        ...base,
        content: {
          state: "exported",
          relative_path: written.paths[outcome.file] ?? file.relativePath,
          ...(written.layouts[outcome.file] ?? {
            layout: file.layout,
            layout_reason: file.layoutReason,
          }),
          sha256: file.body.sha256,
          bytes: file.body.bytes,
          redacted: file.body.redacted,
          representation: file.body.representation,
        },
        view: views.get(outcome.file) ?? null,
      };
    return {
      ...base,
      content:
        outcome?.kind === "redirect"
          ? { state: "redirect", to_transaction_id: outcome.toTransactionId }
          : outcome?.kind === "unavailable"
            ? {
                state: "unavailable",
                reason: outcome.reason,
                message: outcome.message,
              }
            : {
                state: "unavailable",
                reason: "unavailable",
                message: "No bytes were retained.",
              },
      view: null,
    };
  });

const coverage = (
  plan: MirrorPlan,
  records: readonly WebMirrorResource[],
  views: ReadonlyMap<number, ViewRecord>,
): WebMirrorExportResult["coverage"] => {
  const count = (state: WebMirrorResource["content"]["state"]): number =>
    records.filter(({ content }) => content.state === state).length;
  let rewritten = 0;
  let unresolved = 0;
  for (const view of views.values()) {
    rewritten += view.rewritten_references;
    unresolved += view.unresolved_references;
  }
  return {
    transactions: records.length,
    exported: count("exported"),
    files: plan.files.length,
    redirects: count("redirect"),
    unavailable: count("unavailable"),
    views: views.size,
    rewritten_references: rewritten,
    unresolved_references: unresolved,
  };
};

const mirrorLimitations = (
  capture: SelectedMirrorCapture,
  plan: MirrorPlan,
  texts: ReadonlyMap<number, string>,
): string[] => {
  const hasCaptured = capture.resources.some(
    ({ content }) => content.state === "captured",
  );
  return [
    ...capture.limitations,
    ...(hasCaptured &&
    !capture.limitations.includes(
      PLAYWRIGHT_RESPONSE_BODY_PROVENANCE_LIMITATION,
    )
      ? [PLAYWRIGHT_RESPONSE_BODY_PROVENANCE_LIMITATION]
      : []),
    ...LIMITATIONS,
    ...(plan.files.some(
      (file, index) =>
        viewKind(file) !== undefined &&
        URL.canParse(file.url) &&
        !texts.has(index),
    )
      ? [NO_VIEW_LIMITATION]
      : []),
    ...(plan.files.some(
      (file) => viewKind(file) !== undefined && !URL.canParse(file.url),
    )
      ? [NO_URL_VIEW_LIMITATION]
      : []),
    ...(hasCaptured
      ? []
      : [
          "No response bytes were retained. Select capture.network.response_body in capture_browser_scenario, then capture again.",
        ]),
  ];
};

/** The token-lean inline answer; per-resource records stay in the manifest. */
const inlineResult = (
  manifest: ReturnType<typeof webMirrorManifestSchema.parse>,
  descriptor: WebMirrorExportResult["manifest"],
): WebMirrorExportResult => {
  const unavailable = manifest.resources.flatMap(
    ({ url, resource_type, content }) =>
      content.state === "unavailable"
        ? [{ url, resource_type, reason: content.reason }]
        : [],
  );
  return webMirrorExportResultSchema.parse({
    capture: manifest.capture,
    output_directory: manifest.output_directory,
    entry: manifest.entry,
    coverage: manifest.coverage,
    unavailable: unavailable.slice(0, WEB_MIRROR_INLINE_UNAVAILABLE_LIMIT),
    unavailable_omitted: Math.max(
      0,
      unavailable.length - WEB_MIRROR_INLINE_UNAVAILABLE_LIMIT,
    ),
    manifest: descriptor,
    limitations: manifest.limitations,
  });
};

const writeExactFile = async (
  tree: SafeOutputTree,
  file: PlannedMirrorFile,
  bytes: Buffer,
  signal: AbortSignal | undefined,
): Promise<{
  readonly path: string;
  readonly layout: {
    readonly layout: "url-path" | "isolated";
    readonly layout_reason: string | null;
  };
}> => {
  try {
    await writeTreeFile(
      tree,
      file.relativePath,
      bytes,
      file.body.sha256,
      signal,
    );
    return {
      path: file.relativePath,
      layout: { layout: file.layout, layout_reason: file.layoutReason },
    };
  } catch (cause: unknown) {
    const collision =
      destinationCollisionReason(cause) ?? pathTooLongReason(cause);
    if (collision === undefined || file.layout !== "url-path") throw cause;
    await writeTreeFile(
      tree,
      file.isolatedPath,
      bytes,
      file.body.sha256,
      signal,
    );
    return {
      path: file.isolatedPath,
      layout: { layout: "isolated", layout_reason: collision },
    };
  }
};

/** A destination that cannot hold the URL path's length isolates the file. */
const pathTooLongReason = (cause: unknown): string | undefined => {
  for (
    let current: unknown = cause, depth = 0;
    current instanceof Error && depth < 8;
    current = current.cause, depth += 1
  )
    if ("code" in current && current.code === "ENAMETOOLONG")
      return "The destination filesystem rejected the URL path as too long.";
  return undefined;
};

/**
 * Map each captured URL to the file that answers it. A later capture of the
 * same URL wins; redirect hops resolve to their final captured response.
 */
const urlTargets = (
  capture: SelectedMirrorCapture,
  plan: ReturnType<typeof planWebMirror>,
): Map<string, number> => {
  const byTransaction = new Map<string, number>();
  capture.resources.forEach((resource, index) =>
    byTransaction.set(resource.source.transaction_id, index),
  );
  const fileOf = (index: number): number | undefined => {
    let current: number | undefined = index;
    for (
      let hop = 0;
      hop <= MAX_REDIRECT_HOPS && current !== undefined;
      hop++
    ) {
      const outcome = plan.resources[current];
      if (outcome?.kind === "file") return outcome.file;
      if (outcome?.kind !== "redirect") return undefined;
      current = byTransaction.get(outcome.toTransactionId);
    }
    return undefined;
  };
  const targets = new Map<string, number>();
  capture.resources.forEach((resource, index) => {
    const key = mirrorUrlKey(resource.url);
    const file = fileOf(index);
    if (key === null || file === undefined) return;
    // A final response always wins over a redirect hop for the same URL.
    if (plan.resources[index]?.kind === "file" || !targets.has(key))
      targets.set(key, file);
  });
  return targets;
};

const rewriteView = (
  file: PlannedMirrorFile,
  text: string,
  fromPath: string,
  lookup: (url: string) => string | undefined,
): RewriteCounts & { readonly text: string } => {
  // parse5 and the CSS tokenizer report offsets in the decoded text; keep a
  // byte-order mark outside the edited range.
  const bom = text.startsWith("﻿") ? "﻿" : "";
  const body = text.slice(bom.length);
  const documentUrl = new URL(file.url);
  const rewritten =
    viewKind(file) === "html"
      ? rewriteHtml(body, documentUrl, { fromPath, lookup })
      : rewriteCss(body, documentUrl, { fromPath, lookup });
  return { ...rewritten, text: `${bom}${rewritten.text}` };
};

const originOf = (value: string): string | null =>
  URL.canParse(value) ? new URL(value).origin : null;

/**
 * The document the start navigation ended at. When no exported document has
 * that exact URL (a client-side route change, or an uncaptured body), only a
 * same-origin document requested during the start step is accepted, with a
 * limitation naming it; a third-party frame never becomes the entry.
 */
const entryRecord = (
  capture: SelectedMirrorCapture,
  records: readonly WebMirrorResource[],
): {
  readonly entry: WebMirrorExportResult["entry"];
  readonly limitation?: string;
} => {
  const target = mirrorUrlKey(capture.entryUrl);
  const origin = originOf(capture.entryUrl);
  const { first, last } = capture.entrySequences;
  const documents = records.filter(
    (record) =>
      record.resource_type === "document" &&
      record.content.state === "exported",
  );
  const exact = documents.find((record) => mirrorUrlKey(record.url) === target);
  const selected =
    exact ??
    documents.find(
      ({ url, source }) =>
        origin !== null &&
        originOf(url) === origin &&
        source.request_sequence >= first &&
        source.request_sequence <= last,
    );
  if (selected === undefined || selected.content.state !== "exported")
    return {
      entry: null,
      limitation:
        "No captured HTML document matched the start navigation, so no entry page was generated.",
    };
  return {
    entry: {
      url: selected.url,
      file_path: selected.content.relative_path,
      view_path: selected.view?.relative_path ?? null,
      open_path: "index.html",
    },
    ...(exact === undefined
      ? {
          limitation: `The start navigation ended at ${capture.entryUrl}, which matches no captured document; the entry page is ${selected.url}, the first same-origin document requested during that navigation.`,
        }
      : {}),
  };
};

const writeIndexPage = async (
  tree: SafeOutputTree,
  target: string,
  signal: AbortSignal | undefined,
): Promise<void> => {
  const bytes = indexPage(target);
  await writeTreeFile(
    tree,
    "index.html",
    bytes,
    createHash("sha256").update(bytes).digest("hex"),
    signal,
  );
};
